// Language switcher functionality
class LanguageSwitcher {
  constructor() {
    this.currentLang = localStorage.getItem('selectedLanguage') || 'en';
    this.init();
  }

  init() {
    // Set initial language
    document.documentElement.lang = this.currentLang;
    this.updateAllText();

    // Set up language toggle button
    this.setupToggleButton();
  }

  setupToggleButton() {
    const toggle = document.getElementById('lang-toggle');
    if (toggle) {
      toggle.textContent = this.currentLang === 'en' ? 'తెలుగు' : 'English';
      toggle.addEventListener('click', () => this.switchLanguage());
    }
  }

  switchLanguage() {
    this.currentLang = this.currentLang === 'en' ? 'te' : 'en';
    localStorage.setItem('selectedLanguage', this.currentLang);
    document.documentElement.lang = this.currentLang;
    this.updateAllText();
    this.setupToggleButton();
  }

  updateAllText() {
    // Update all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(element => {
      const key = element.dataset.i18n;
      if (translations[this.currentLang][key]) {
        element.textContent = translations[this.currentLang][key];
      }
    });

    // Update placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
      const key = element.dataset.i18nPlaceholder;
      if (translations[this.currentLang][key]) {
        element.placeholder = translations[this.currentLang][key];
      }
    });
  }

  getText(key) {
    return translations[this.currentLang][key] || key;
  }
}

// Initialize when DOM is ready
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', () => {
    window.languageSwitcher = new LanguageSwitcher();
  });
} else {
  window.languageSwitcher = new LanguageSwitcher();
}
